#!/usr/bin/env python3
"""Owned exact dyadics for native integral rounding and integer conversion."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
def main():
    base=[bytes.fromhex(s) for s in (ROOT/'probes/sane/base-operands.txt').read_text().splitlines()]
    common=(ROOT/'probes/sane/operands.bin').read_bytes()
    values=base+[common[(38+514+i*3)*10:(38+514+i*3+1)*10] for i in range(32)]
    anchors=[-2147483649,-2147483648,-2147483647,-32769,-32768,-32767,-2,-1,0,1,2,32766,32767,32768,2147483646,2147483647,2147483648]
    for anchor in anchors:
        for offset in range(-3,4):
            n=4*anchor+offset;sign=0x8000 if n<0 else 0;n=abs(n)
            if n:
                length=n.bit_length();value=(sign+16383+length-3).to_bytes(2,'big')+(n<<(64-length)).to_bytes(8,'big')
            else:value=bytes(10)
            values.append(value)
    assert len(values)==189 and all(len(b)==10 for b in values)
    header='/* Owned exact inputs; generated by tools/build-sane-round-operands.py. */\n#define ROUND_COUNT 189\nstatic const unsigned char round_operands[][10]={\n'+''.join('{'+','.join(map(str,b))+'},\n'for b in values)+'};\n'
    for name,data in [('operands.bin',b''.join(values)),('operands.h',header.encode())]:
        path=ROOT/'probes/saneround'/name
        if '--check' in sys.argv:assert path.read_bytes()==data
        elif not path.exists() or path.read_bytes()!=data:path.write_bytes(data)
    print('Owned integral rounding inputs:',len(values))
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Build one owned TimerProc instruction image for native and independent use."""
from pathlib import Path
import subprocess
ROOT=Path(__file__).resolve().parents[1];SOURCE=ROOT/'probes/timemanager';WORK=ROOT/'work/probes/timer-image'
def main():
    WORK.mkdir(parents=True,exist_ok=True);tool=ROOT/'work/Retro68-build/toolchain/bin'
    subprocess.run([tool/'m68k-apple-macos-as','-m68020','-o',WORK/'callback.o',SOURCE/'callback.s'],check=True)
    reloc=subprocess.check_output([tool/'m68k-apple-macos-objdump','-r',WORK/'callback.o'],text=True)
    assert 'R_68' not in reloc
    subprocess.run([tool/'m68k-apple-macos-objcopy','-O','binary','-j','.text',WORK/'callback.o',SOURCE/'callback.bin'],check=True)
    image=(SOURCE/'callback.bin').read_bytes();assert image[-2:]==b'\x4e\x75'
    (SOURCE/'callback.h').write_text('/* Generated by tools/build-timer-callback.py. */\nstatic const unsigned char timer_callback[] __attribute__((aligned(2))) = {'+','.join(f'0x{b:02x}' for b in image)+'};\n')
    print('Owned TimerProc: '+str(len(image))+' bytes')
if __name__=='__main__':main()

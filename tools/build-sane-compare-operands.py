#!/usr/bin/env python3
"""Owned exact dyadics and pinned shared fixtures for SANE quiet/signaling comparison calls."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
def main():
    ext=(ROOT/'probes/sane/operands.bin').read_bytes();double=(ROOT/'probes/sanewiden/operands.bin').read_bytes()
    dests=[2,2,4,6,2,3,20,17,0,1,2,3,2,2,6,7,15,16,20,6,2,3,36,32,2,27,35,24,37,2,24,36]
    x=[];d=[];dest=[]
    for i in range(64):
        si=i if i<32 else 80+((i-32)*3)%128;di=dests[i]if i<32 else 38+514+((i-32)*3+37)%128
        xi=i if i<32 else 38+514+((i-32)*3)%128
        x.append(ext[xi*10:xi*10+10]);d.append(double[si*8:si*8+8]);dest.append(ext[di*10:di*10+10])
    def dyadic(n,shift):
        sign=32768 if n<0 else 0;n=abs(n)
        if not n:return bytes(10)
        length=n.bit_length();return(sign|16383+length-1-shift).to_bytes(2,'big')+(n<<(64-length)).to_bytes(8,'big')
    for n in [0,1,2,126,127,128,129,255,256,257,-1,-2,-126,-127,-128,-129]:
        for offset in [-2,-1,0,1]:
            negative=(len(dest)//4)&1
            x.append(dyadic(-3 if negative else 3,1));d.append((0xbff8000000000000 if negative else 0x3ff8000000000000).to_bytes(8,'big'));dest.append(dyadic((4*n+offset)*3,3))
    assert len(x)==len(d)==len(dest)==128
    header='/* Owned comparison inputs; generated by tools/build-sane-rem-operands.py. */\n#define COMPARE_COUNT 128\n'
    for name,values,width in [('cmp_sources_x',x,10),('cmp_sources_d',d,8),('cmp_destinations',dest,10)]:header+='static const unsigned char '+name+'[][ '+str(width)+' ]={\n'+''.join('{'+','.join(map(str,b))+'},\n'for b in values)+'};\n'
    for name,data in [('operands.h',header.encode()),('sources_x.bin',b''.join(x)),('sources_d.bin',b''.join(d)),('destinations.bin',b''.join(dest))]:
        p=ROOT/'probes/sanecompare'/name
        if '--check'in sys.argv:assert p.read_bytes()==data
        elif not p.exists()or p.read_bytes()!=data:p.write_bytes(data)
    print('Owned comparison pairs:',len(dest),'for each source format')
if __name__=='__main__':main()

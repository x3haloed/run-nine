#!/usr/bin/env python3
"""Assemble our position-independent probe once for native/hosted/bare-metal use."""
from pathlib import Path
import subprocess
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'probes/owned68k';WORK=ROOT/'work/probes/owned68k-image'
def main():
    WORK.mkdir(parents=True,exist_ok=True)
    tool=ROOT/'work/Retro68-build/toolchain/bin'
    subprocess.run([tool/'m68k-apple-macos-as','-m68020','-o',WORK/'program.o',SOURCE/'program.s'],check=True)
    reloc=subprocess.check_output([tool/'m68k-apple-macos-objdump','-r',WORK/'program.o'],text=True)
    if 'R_68' in reloc:raise RuntimeError('Owned instruction image contains unresolved relocations')
    subprocess.run([tool/'m68k-apple-macos-objcopy','-O','binary','-j','.text',WORK/'program.o',SOURCE/'program.bin'],check=True)
    image=(SOURCE/'program.bin').read_bytes()
    assert 0<len(image)<=4096 and image[-2:]==b'\x4e\x75'
    (SOURCE/'program.h').write_text('/* Generated by tools/build-owned68k.py; identical bytes in all three environments. */\nstatic const unsigned char owned68k_program[] __attribute__((aligned(2))) = {\n'+','.join(f'0x{b:02x}' for b in image)+'\n};\n')
    print(f'Owned position-independent 68K image: {len(image)} bytes')
if __name__=='__main__':main()
